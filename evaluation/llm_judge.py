"""
LLM-as-Judge evaluation for reply quality.

Uses Groq (Llama 3.1 70B) to evaluate generated replies on 5 dimensions:
1. Relevance — Does the reply address the customer's issue?
2. Tone — Is it empathetic and brand-consistent?
3. Actionability — Does it provide clear next steps?
4. Groundedness — Is it consistent with real Amazon practices?
5. Conciseness — Is it appropriately brief for Twitter?

Each dimension is scored 1-5.
"""

import json
import time
import sys
from pathlib import Path

from groq import Groq

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.config import (
    GROQ_API_KEY,
    LLM_MODEL_JUDGE,
    LLM_TEMPERATURE_JUDGE,
    GROQ_DELAY_SECONDS,
)


JUDGE_RUBRIC = """You are an expert evaluator of customer support replies. You are evaluating a reply generated by an AI agent for AmazonHelp on Twitter.

## Scoring Rubric (1-5 scale):

### Relevance
1 = Completely ignores the customer's issue, irrelevant response
2 = Vaguely related but misses the main point  
3 = Addresses the general topic but misses specifics
4 = Addresses the specific issue well
5 = Perfectly addresses every aspect of the customer's message

### Tone  
1 = Rude, dismissive, or robotic/generic
2 = Neutral but feels automated, lacks empathy
3 = Professional but somewhat impersonal
4 = Friendly, empathetic, and professional  
5 = Perfectly matches a caring brand voice — warm, genuine, human

### Actionability
1 = No next steps whatsoever
2 = Vague suggestion (e.g., "contact us")
3 = Some guidance but not specific enough
4 = Clear next steps with specific instructions
5 = Excellent — specific, actionable, easy-to-follow steps

### Groundedness
1 = Contains obviously false information or hallucinated policies
2 = Plausible but unverifiable or speculative claims
3 = Generic but not clearly wrong
4 = Consistent with known Amazon practices
5 = Clearly grounded in real Amazon customer service patterns

### Conciseness
1 = Extremely verbose, rambling, way too long for Twitter
2 = Too long, could be significantly shortened
3 = Acceptable length but slightly wordy
4 = Well-sized for the platform
5 = Perfectly concise — says everything needed in minimal words

Return your evaluation as JSON:
{
    "relevance": <1-5>,
    "tone": <1-5>,
    "actionability": <1-5>,
    "groundedness": <1-5>,
    "conciseness": <1-5>,
    "overall": <1-5>,
    "reasoning": "<brief explanation of your scores>"
}"""


class LLMJudge:
    """
    LLM-as-judge for evaluating reply quality.
    
    Uses a structured rubric to score replies on 5 dimensions.
    """
    
    def __init__(self):
        if not GROQ_API_KEY:
            raise ValueError("GROQ_API_KEY not set!")
        
        self.client = Groq(api_key=GROQ_API_KEY)
        self.model = LLM_MODEL_JUDGE
        print(f"[✓] LLMJudge initialized (model: {self.model})")
    
    def evaluate_reply(
        self,
        customer_message: str,
        generated_reply: str,
        intent: str = "",
        actual_reply: str = "",
    ) -> dict:
        """
        Evaluate a single generated reply.
        
        Args:
            customer_message: The original customer message.
            generated_reply: The AI-generated reply to evaluate.
            intent: The classified intent (for context).
            actual_reply: The actual AmazonHelp reply (optional, for comparison).
        
        Returns:
            Dict with scores for each dimension and overall.
        """
        prompt = self._build_judge_prompt(
            customer_message, generated_reply, intent, actual_reply
        )
        
        try:
            time.sleep(GROQ_DELAY_SECONDS)
            
            response = self.client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": JUDGE_RUBRIC},
                    {"role": "user", "content": prompt},
                ],
                temperature=LLM_TEMPERATURE_JUDGE,
                max_tokens=500,
            )
            
            raw = response.choices[0].message.content.strip()
            return self._parse_scores(raw)
            
        except Exception as e:
            print(f"[⚠] Judge error: {e}")
            return {
                "relevance": 0, "tone": 0, "actionability": 0,
                "groundedness": 0, "conciseness": 0, "overall": 0,
                "reasoning": f"Error: {e}",
                "error": True,
            }
    
    def evaluate_batch(self, examples: list) -> list:
        """
        Evaluate a batch of examples.
        
        Args:
            examples: List of dicts with keys: customer_message, generated_reply,
                     intent (optional), actual_reply (optional).
        
        Returns:
            List of score dicts.
        """
        results = []
        for i, ex in enumerate(examples):
            print(f"    Judging {i+1}/{len(examples)}...")
            score = self.evaluate_reply(
                customer_message=ex["customer_message"],
                generated_reply=ex["generated_reply"],
                intent=ex.get("intent", ""),
                actual_reply=ex.get("actual_reply", ""),
            )
            results.append(score)
        return results
    
    def _build_judge_prompt(
        self,
        customer_message: str,
        generated_reply: str,
        intent: str,
        actual_reply: str,
    ) -> str:
        """Build the evaluation prompt."""
        prompt = f"""Evaluate this customer support interaction:

## Customer Message:
"{customer_message}"

## Intent: {intent if intent else "not specified"}

## AI-Generated Reply:
"{generated_reply}"
"""
        
        if actual_reply:
            prompt += f"""
## Actual AmazonHelp Reply (for reference):
"{actual_reply}"
"""
        
        prompt += """
Score the AI-generated reply on each dimension (1-5) and provide your reasoning.
Return ONLY valid JSON."""
        
        return prompt
    
    def _parse_scores(self, raw: str) -> dict:
        """Parse the judge's JSON response."""
        try:
            # Clean markdown code blocks
            cleaned = raw.strip()
            if cleaned.startswith("```"):
                cleaned = cleaned.split("```")[1]
                if cleaned.startswith("json"):
                    cleaned = cleaned[4:]
                cleaned = cleaned.strip()
            
            result = json.loads(cleaned)
            
            # Validate and clamp scores
            dimensions = ["relevance", "tone", "actionability", "groundedness", "conciseness", "overall"]
            for dim in dimensions:
                if dim in result:
                    result[dim] = max(1, min(5, int(result[dim])))
                else:
                    result[dim] = 3  # Default to median
            
            return result
            
        except (json.JSONDecodeError, ValueError, TypeError):
            # Try to extract scores from text
            return self._extract_scores_from_text(raw)
    
    def _extract_scores_from_text(self, raw: str) -> dict:
        """Fallback: extract scores from free-text judge output."""
        import re
        
        scores = {
            "relevance": 3, "tone": 3, "actionability": 3,
            "groundedness": 3, "conciseness": 3, "overall": 3,
            "reasoning": raw[:200],
        }
        
        for dim in scores:
            if dim == "reasoning":
                continue
            pattern = rf'{dim}["\s:]*(\d)'
            match = re.search(pattern, raw.lower())
            if match:
                scores[dim] = max(1, min(5, int(match.group(1))))
        
        return scores


def compute_judge_summary(scores: list) -> dict:
    """
    Compute summary statistics from a batch of judge scores.
    
    Args:
        scores: List of score dicts from the judge.
    
    Returns:
        Summary with averages per dimension and overall.
    """
    import numpy as np
    
    dimensions = ["relevance", "tone", "actionability", "groundedness", "conciseness"]
    
    # Filter out errors
    valid_scores = [s for s in scores if not s.get("error")]
    
    if not valid_scores:
        return {"error": "No valid scores to summarize"}
    
    dimension_averages = {}
    for dim in dimensions:
        values = [s[dim] for s in valid_scores if dim in s and s[dim] > 0]
        if values:
            dimension_averages[dim] = round(np.mean(values), 3)
    
    overall_values = [s.get("overall", 0) for s in valid_scores if s.get("overall", 0) > 0]
    
    return {
        "dimension_averages": dimension_averages,
        "overall_average": round(np.mean(overall_values), 3) if overall_values else 0,
        "num_evaluated": len(valid_scores),
        "num_errors": len(scores) - len(valid_scores),
        "score_distribution": {
            dim: {
                "min": min(s[dim] for s in valid_scores if s.get(dim, 0) > 0),
                "max": max(s[dim] for s in valid_scores if s.get(dim, 0) > 0),
                "std": round(np.std([s[dim] for s in valid_scores if s.get(dim, 0) > 0]), 3),
            }
            for dim in dimensions
            if any(s.get(dim, 0) > 0 for s in valid_scores)
        },
    }
